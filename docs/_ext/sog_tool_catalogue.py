"""Sphinx extension: generate the tool-catalogue pages at build time.

The pages under ``docs/tools/`` are **generated**, never edited by hand, so the documentation can
not drift from the platform it describes. Three tracked sources feed them:

* ``install/recipes/tool_specs/<key>.yaml`` — one spec per MCP server: its portal and worker files,
  the conda env it runs in, whether it wants a GPU, and the analysis *category* of each function.
* ``agent/MCP_server/mcp_config.yaml`` — the canonical MCP config: each server's description and,
  for each function, its description and parameters (type, required, default, description).
* ``agent/spatialomicsgym/tool/tool_description/<subject>.py`` — the in-process research tools
  (plain Python literals; they are read with :func:`ast.literal_eval`, never imported or executed).

This is the same material ``python -m sog_install.tools_catalog --write`` renders into
``agent/tools/CATALOG.md``; here it is split into one page per category, with the function
parameters that the one-line catalogue leaves out.

The extension runs on Sphinx's ``builder-inited`` event, before any source file is read, and
writes Markdown (MyST) files. It needs only the standard library and PyYAML. Run it directly
(``python docs/_ext/sog_tool_catalogue.py``) to regenerate the pages without a Sphinx build.
"""

