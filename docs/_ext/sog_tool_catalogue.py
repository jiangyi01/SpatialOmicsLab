def _on_builder_inited(app: Sphinx) -> None:
    from sphinx.util import logging

    logger = logging.getLogger(__name__)
    try:
        written = generate(Path(app.srcdir) / "tools")
    except FileNotFoundError as exc:
        logger.warning("tool catalogue not generated: %s", exc)
        return
    logger.info("tool catalogue: %d page(s) (re)generated under docs/tools/", len(written))


def setup(app: Sphinx) -> dict[str, Any]:
    app.connect("builder-inited", _on_builder_inited)
    return {"version": "1.0", "parallel_read_safe": True, "parallel_write_safe": True}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/tools/*.md from the tool specs and the MCP config.")
    parser.add_argument("--output", type=Path, default=OUTPUT_DIR, help=f"directory to write (default: {OUTPUT_DIR})")
    args = parser.parse_args(argv)
    written = generate(args.output)
    for path in written:
        print(f"wrote {path.relative_to(REPO_ROOT) if path.is_relative_to(REPO_ROOT) else path}")
    print(f"{len(written)} page(s) written to {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
