_ESCAPES = str.maketrans({"*": r"\*", "_": r"\_", "[": r"\[", "]": r"\]", "<": "&lt;", ">": "&gt;", "|": r"\|"})


def md_text(text: str, *, in_table: bool = False) -> str:
    """Escape prose for MyST while keeping balanced backtick code spans intact."""
    text = " ".join(str(text or "").split())
    if text.count("`") % 2:
        text = text.replace("`", "")
    out: list[str] = []
    for i, chunk in enumerate(text.split("`")):
        if i % 2:  # inside a code span: only the table delimiter needs care
            out.append("`" + (chunk.replace("|", "\\|") if in_table else chunk) + "`")
        else:
            escaped = chunk.translate(_ESCAPES)
            if not in_table:
                escaped = escaped.replace("\\|", "|")
            out.append(escaped)
    return "".join(out)


def md_code(value: Any, *, in_table: bool = False) -> str:
    """A code span; inside a table the cell delimiter is escaped (markdown-it drops the backslash again)."""
    text = str(value).replace("`", "")
    if in_table:
        text = text.replace("|", "\\|")
    return f"`{text}`" if text else ""


def md_default(param: dict[str, Any]) -> str:
    """The default of a parameter as a table cell: ``—`` when there is none."""
    default = param.get("default")
    if default is None:
        return "—"
    if isinstance(default, bool):
        return md_code(str(default).lower(), in_table=True)
    if isinstance(default, str):
        return md_code(f'"{default}"' if default else '""', in_table=True)
    return md_code(default, in_table=True)


def split_description(text: str) -> tuple[str, str]:
    """Split a function description into (what it does, data requirements)."""
    if DATA_REQUIREMENTS_MARKER in text:
        head, _, tail = text.partition(DATA_REQUIREMENTS_MARKER)
        return head.strip(), tail.strip()
    return text.strip(), ""


def table(header: list[str], rows: list[list[str]], align: list[str] | None = None) -> str:
    align = align or ["---"] * len(header)
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join(align) + " |"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(lines)


def slug(heading: str) -> str:
    """The anchor MyST gives a heading (``myst_heading_anchors``): lower-case, spaces to ``-``, punctuation dropped."""
    return re.sub(r"[^\w一-鿿\- ]", "", heading.strip().lower().replace(" ", "-"))


def category_title(category: str) -> str:
    if category in CATEGORIES:
        return CATEGORIES[category][0]
    return category.replace("_", " ").capitalize()


def category_order(servers: dict[str, Server]) -> list[str]:
    seen = {fn.category for s in servers.values() for fn in s.functions}
    known = [c for c in CATEGORIES if c in seen]
    extra = sorted(c for c in seen if c not in CATEGORIES and c != UNCATEGORISED)
    tail = [UNCATEGORISED] if UNCATEGORISED in seen else []
    return known + extra + tail


