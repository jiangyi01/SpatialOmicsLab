@dataclass
class Function:
    name: str
    category: str = UNCATEGORISED
    description: str = ""
    parameters: list[dict[str, Any]] = field(default_factory=list)
    wired: bool = True  # False: in the spec, but absent from the canonical config


@dataclass
class Server:
    key: str
    portal: str = ""
    worker: str = ""
    worker_kind: str = ""
    env: str = ""
    builds_env: bool = True
    gpu: bool = False
    est_gb: float | None = None
    description: str = ""
    enabled: bool = True
    functions: list[Function] = field(default_factory=list)

    @property
    def primary_category(self) -> str:
        return self.functions[0].category if self.functions else UNCATEGORISED

    @property
    def categories(self) -> list[str]:
        seen: list[str] = []
        for fn in self.functions:
            if fn.category not in seen:
                seen.append(fn.category)
        return seen


@dataclass
class InProcessTool:
    name: str
    module: str
    description: str
    required: list[dict[str, Any]]
    optional: list[dict[str, Any]]


