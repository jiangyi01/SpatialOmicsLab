def _write(path: Path, text: str) -> bool:
    """Write ``text`` to ``path`` if it changed; return whether it was written (keeps rebuilds incremental)."""
    if not text.endswith("\n"):
        text += "\n"
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return True


def substitutions() -> dict[str, str]:
    """The headline counts, for ``myst_substitutions``: ``{{ n_servers }}`` and friends in hand-written pages."""
    servers = read_servers()
    in_process = read_in_process_tools()
    n_servers = len(servers)
    n_functions = sum(1 for s in servers.values() for fn in s.functions if fn.wired)
    n_in_process = sum(len(v) for v in in_process.values())
    return {
        "n_servers": str(n_servers),
        "n_mcp_functions": str(n_functions),
        "n_in_process": str(n_in_process),
        "n_tools_total": str(n_functions + n_in_process),
    }


def generate(output_dir: Path = OUTPUT_DIR) -> list[Path]:
    servers = read_servers()
    in_process = read_in_process_tools()
    written: list[Path] = []
    pages = {"index.md": render_index(servers, in_process), "in-process.md": render_in_process(in_process)}
    for category in category_order(servers):
        pages[f"{category}.md"] = render_category(category, servers)
    for name, text in pages.items():
        if _write(output_dir / name, text):
            written.append(output_dir / name)
    # Remove pages for categories that no longer exist, so a stale file never lingers in the toctree.
    for stale in output_dir.glob("*.md"):
        if stale.name not in pages:
            stale.unlink()
    return written


