def _env_of_interpreter(path: str) -> str:
    """``.../envs/<name>/bin/python`` -> ``<name>``; a base ``bin/`` -> ``base``; otherwise ``""``."""
    parts = Path(str(path)).parts
    if "envs" in parts:
        i = parts.index("envs")
        if i + 1 < len(parts):
            return parts[i + 1]
    return "base" if "bin" in parts else ""


def _interpreter_env(env_vars: dict[str, Any]) -> str:
    for var in sorted(env_vars):
        if var.endswith(("_PYTHON", "_RSCRIPT")):
            name = _env_of_interpreter(env_vars[var])
            if name:
                return name
    return ""


def read_servers(specs_dir: Path = SPECS_DIR, config_path: Path = CONFIG_PATH) -> dict[str, Server]:
    """Merge the tool specs with the canonical MCP config into one :class:`Server` per key."""
    config = (yaml.safe_load(config_path.read_text(encoding="utf-8")) or {}).get("mcp_servers") or {}
    specs: dict[str, dict[str, Any]] = {}
    for spec_file in sorted(specs_dir.glob("*.yaml")):
        spec = yaml.safe_load(spec_file.read_text(encoding="utf-8")) or {}
        if not isinstance(spec, dict) or not spec.get("server_key"):
            continue  # index.yaml and the like are not server specs
        specs[spec["server_key"]] = spec

    servers: dict[str, Server] = {}
    for key in sorted(set(specs) | set(config)):
        spec = specs.get(key, {})
        entry = config.get(key) or {}
        server = Server(key=key)

        # Files, env and hardware come from the spec; the config is the fallback.
        server.portal = spec.get("server_file") or next(
            (Path(str(a)).name for a in entry.get("command") or [] if str(a).endswith(".py")), ""
        )
        server.worker = spec.get("worker_file") or next(
            (Path(str(v)).name for k, v in sorted((entry.get("env") or {}).items()) if k.endswith("_WORKER") and v),
            "",
        )
        kind = str(spec.get("worker_kind") or "").lower()
        server.worker_kind = "r" if kind.startswith("r") or server.worker.endswith(".R") else "python"
        if spec.get("source_env"):
            server.env = str(spec["source_env"])
            server.builds_env = True
        else:
            server.env = _interpreter_env(spec.get("override_vars") or entry.get("env") or {})
            server.builds_env = False
        server.gpu = bool(spec.get("gpu", False))
        server.est_gb = spec.get("est_gb")
        server.description = " ".join(str(entry.get("description") or "").split())
        server.enabled = entry.get("enabled", True) is not False

        categories = {
            f["name"]: f.get("category") or UNCATEGORISED for f in spec.get("functions") or [] if f.get("name")
        }
        for tool in entry.get("tools") or []:
            name = tool.get("spatialomicsgym_name")
            if not name:
                continue
            params = []
            for pname, pinfo in (tool.get("parameters") or {}).items():
                pinfo = pinfo or {}
                params.append(
                    {
                        "name": pname,
                        "type": pinfo.get("type", ""),
                        "required": bool(pinfo.get("required", False)),
                        "default": pinfo.get("default"),
                        "description": " ".join(str(pinfo.get("description") or "").split()),
                    }
                )
            server.functions.append(
                Function(
                    name=name,
                    category=categories.get(name, UNCATEGORISED),
                    description=" ".join(str(tool.get("description") or "").split()),
                    parameters=params,
                )
            )
        # A function the spec knows but the config does not wire still gets a row, without parameters.
        for name, category in categories.items():
            if all(fn.name != name for fn in server.functions):
                server.functions.append(Function(name=name, category=category, wired=False))
        servers[key] = server
    return servers


def read_in_process_tools(descriptions_dir: Path = TOOL_DESCRIPTIONS_DIR) -> dict[str, list[InProcessTool]]:
    """Read the ``description = [...]`` literal of every ``tool_description/<subject>.py`` without importing it."""
    by_module: dict[str, list[InProcessTool]] = {}
    for py in sorted(descriptions_dir.glob("*.py")):
        if py.name.startswith("_"):
            continue
        tree = ast.parse(py.read_text(encoding="utf-8"), filename=str(py))
        entries: list[Any] = []
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "description" for t in node.targets):
                try:
                    entries = ast.literal_eval(node.value)
                except (ValueError, SyntaxError):
                    entries = []
                break
        tools = [
            InProcessTool(
                name=str(e.get("name", "")),
                module=py.stem,
                description=" ".join(str(e.get("description") or "").split()),
                required=list(e.get("required_parameters") or []),
                optional=list(e.get("optional_parameters") or []),
            )
            for e in entries
            if isinstance(e, dict) and e.get("name")
        ]
        if tools:
            by_module[py.stem] = tools
    return by_module


